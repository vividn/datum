import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { sveltekit } from '@sveltejs/kit/vite';
import { defineConfig, type Plugin, type ViteDevServer, type PreviewServer } from 'vite';
import { execFileSync } from 'node:child_process';

/**
 * What is actually running, injected at build time.
 *
 * A deployed static bundle is otherwise anonymous: the only way to tell which
 * commit is live is to compare hashed asset names against a local build, which
 * is exactly the fiddly step this removes.
 *
 * CI's `GITHUB_SHA` wins over `git rev-parse` because a CI checkout can be a
 * detached merge commit that exists nowhere else — the SHA the workflow was
 * triggered for is the honest answer. A build from a dirty tree says so, since
 * a hash that does not describe the working tree is worse than no hash.
 */
/** The app's own version, from package.json — one source, not a second copy. */
function pkgVersion(): string {
	try {
		const raw = fs.readFileSync(fileURLToPath(new URL('./package.json', import.meta.url)), 'utf8');
		return (JSON.parse(raw) as { version?: string }).version ?? '0.0.0';
	} catch {
		return '0.0.0';
	}
}

function buildVersion(): string {
	const env = process.env.GITHUB_SHA;
	if (env) return env.slice(0, 7);
	try {
		const sha = execFileSync('git', ['rev-parse', '--short=7', 'HEAD'], { encoding: 'utf8' }).trim();
		const dirty = execFileSync('git', ['status', '--porcelain'], { encoding: 'utf8' }).trim();
		return dirty ? `${sha}+` : sha;
	} catch {
		// A tarball with no .git, or no git binary. Unknown is honest; a
		// fabricated or empty string would read as a real build id.
		return 'unknown';
	}
}

// Cross-origin isolation, which the browser grants a document only when
// its response carries both of these headers.
//
// The database does not depend on it: the CLI runs in a worker
// ($lib/db.worker.ts) on that worker's sync access handles, so entries
// persist with or without isolation. The headers stay for what isolation
// still buys — SharedArrayBuffer and Atomics, which a threaded wasm CLI
// would need — and the deployment should keep sending them.
const CROSS_ORIGIN_ISOLATION = {
	'Cross-Origin-Opener-Policy': 'same-origin',
	'Cross-Origin-Embedder-Policy': 'require-corp'
};

/**
 * Set the isolation headers on every dev and preview response.
 *
 * Vite's `server.headers` option is not enough: it applies to Vite's own
 * static middleware, while SvelteKit's SSR handler writes the HTML response
 * (the one that has to be isolated) with headers of its own. Middleware
 * installed here runs ahead of both.
 *
 * The production bundle is static, so the deployment — Scaleway bucket
 * behind Cloudflare — should emit the same two headers.
 */
function crossOriginIsolation(): Plugin {
	const install = (server: ViteDevServer | PreviewServer) => {
		server.middlewares.use((_req, res, next) => {
			for (const [name, value] of Object.entries(CROSS_ORIGIN_ISOLATION)) {
				res.setHeader(name, value);
			}
			next();
		});
	};

	return {
		name: 'datum-cross-origin-isolation',
		configureServer(server) {
			install(server);
		},
		configurePreviewServer(server) {
			install(server);
		}
	};
}

// Where Vite puts the worker bundle, and the module the service worker
// reads it back from.
const WORKER_DIR = '_app/immutable/workers';
const WORKER_ASSETS_MODULE = fileURLToPath(
	new URL('./src/lib/workerAssets.generated.ts', import.meta.url)
);

/**
 * Hand the service worker the names of the files in Vite's worker bundle.
 *
 * `$service-worker`'s `build` list is derived from the *client* Vite
 * manifest, and Vite compiles workers in a rollup pass of their own whose
 * output never lands in that manifest. So the SQLite worker, its chunks,
 * the OPFS async proxy and sqlite3.wasm — together more than half the
 * payload — were absent from the precache, and the database could not open
 * with no network (da-d1l9): offline the fetch handler fell through to the
 * cached '/' HTML, so a request for a wasm module resolved to a document.
 *
 * Those files *are* in the client build's own bundle, which is what this
 * reads. It writes them before SvelteKit's separate service-worker build
 * imports the module, because that build runs after this one finishes.
 */
function workerPrecache(): Plugin {
	const write = (paths: string[]) =>
		fs.writeFileSync(
			WORKER_ASSETS_MODULE,
			'// AUTO-GENERATED by the datum-worker-precache plugin in vite.config.ts — DO NOT EDIT.\n' +
				'// The files Vite emits for $lib/db.worker.ts, for the service worker to precache.\n\n' +
				`export const workerAssets: string[] = ${JSON.stringify(paths, null, '\t')};\n`
		);

	return {
		name: 'datum-worker-precache',
		buildStart() {
			// `vite dev`, and the first build of a fresh checkout, both need
			// the module to exist before anything imports it.
			if (!fs.existsSync(WORKER_ASSETS_MODULE)) write([]);
		},
		generateBundle(_options, bundle) {
			const paths = Object.keys(bundle)
				.filter((name) => name.startsWith(`${WORKER_DIR}/`))
				.map((name) => `/${name}`)
				.sort();
			// Only the client pass emits these; the server pass must not
			// overwrite the list with its own emptiness.
			if (paths.length > 0) write(paths);
		}
	};
}

export default defineConfig({
	define: {
		__DATUM_VERSION__: JSON.stringify(pkgVersion()),
		__DATUM_COMMIT__: JSON.stringify(buildVersion())
	},
	plugins: [sveltekit(), crossOriginIsolation(), workerPrecache()],
	// The database worker ($lib/db.worker.ts) is a module worker; Vite's
	// default worker format — iife — cannot code-split.
	worker: {
		format: 'es'
	}
});
