//! D3 — verb/alias rework acceptance tests (da-gnj.3).
//!
//! Exercises the verb/alias system end-to-end:
//!   * `end` and `stop` are synonyms (both → `Verb::Switch`).
//!   * Spec `default_verb` auto-generates a bare-field alias.
//!   * Cross-field state-alias collisions are skipped on save.
//!   * `<field> end` rewrites to `end <field>` in the CLI pre-pass.
//!   * `<field>e` alias is generated for start/switch-capable fields.
//!   * `datum add` infers shape from `start_time=` / `end_time=` / `dur=` keys.
//!   * `datum add … dur=null` force-resolves to `EntryShape::Point`.
//!   * Alias-expanded invocations populate `entry.alias_chain`.
//!   * `datum why <id>` renders the alias chain without erroring.

mod common;

use common::run_cli;
use datum_core::action::Action;
use datum_core::db::AliasConflictReason;
use datum_core::entry::{EntryShape, Verb};
use datum_core::test_util::{fresh_db, spec_builder};
use serde_json::json;

// ─── 1. `end` and `stop` are synonyms ────────────────────────────────────────

/// `datum end <field>` and `datum stop <field>` land identical rows (modulo
/// hid/slug): both produce `Verb::Switch`. Covers the D3 ruling that `end`/`stop`
/// are user-facing synonyms, neither canonical.
#[test]
fn end_and_stop_are_synonyms() {
    let db_end = fresh_db();
    let db_stop = fresh_db();

    run_cli(&["start", "nap", "-t", "08:00"], &db_end).expect("seed start");
    run_cli(&["end", "nap", "-t", "09:00"], &db_end).expect("end nap");

    run_cli(&["start", "nap", "-t", "08:00"], &db_stop).expect("seed start");
    run_cli(&["stop", "nap", "-t", "09:00"], &db_stop).expect("stop nap");

    let end_entries = db_end.entries_for_field("nap", None).unwrap();
    let stop_entries = db_stop.entries_for_field("nap", None).unwrap();
    assert_eq!(end_entries.len(), 2);
    assert_eq!(stop_entries.len(), 2);

    // Both terminators route to Verb::Switch — the canonical closing verb.
    let end_close = &end_entries.iter().find(|e| e.verb == Verb::Switch).unwrap();
    let stop_close = &stop_entries
        .iter()
        .find(|e| e.verb == Verb::Switch)
        .unwrap();
    assert_eq!(end_close.verb, Verb::Switch);
    assert_eq!(stop_close.verb, Verb::Switch);
    assert_eq!(end_close.field, stop_close.field);
    assert_eq!(end_close.state, stop_close.state);
}

// ─── 2. Auto-generated bare-field alias ──────────────────────────────────────

/// A spec with `default_verb = Switch` and `allowed_states = [happy, sad]`
/// must emit a bare-field alias (`mood` → `switch mood`) so that a typed
/// `datum mood …` lands in the switch path with the trailing args preserved.
#[test]
fn default_verb_in_spec_autogenerates_bare_alias() {
    let db = fresh_db();

    spec_builder("mood").default_verb(Action::Switch).save(&db);
    let mut spec = db.load_spec("mood").unwrap().unwrap();
    spec.allowed_states = Some(vec!["happy".into(), "sad".into()]);
    spec.regenerate_derived_aliases();
    db.save_field_spec(&spec).unwrap();

    // The bare-field alias is present and expands via the default_verb.
    let bare = db.lookup_alias("mood").unwrap().expect("bare-field alias");
    assert_eq!(bare.expands_to, "switch mood");

    // `datum mood happy` composes: alias expands `mood` → `switch mood`,
    // `happy` becomes the positional value, and the row writes as Switch.
    run_cli(&["mood", "happy"], &db).expect("bare alias dispatch");
    let entries = db.entries_for_field("mood", None).unwrap();
    assert_eq!(entries.len(), 1);
    assert_eq!(entries[0].verb, Verb::Switch);
    assert_eq!(entries[0].state.as_ref(), Some(&json!("happy")));
}

// ─── 3. Cross-field state-alias collision ────────────────────────────────────

/// Two specs declaring the same state name emit colliding state aliases. The
/// second save surfaces the collision via `save_field_spec_with_report` and
/// leaves the first-saved spec's alias intact (first-save wins).
#[test]
fn autogenerated_state_alias_skipped_on_conflict() {
    let db = fresh_db();

    // First spec owns the 'happy' alias.
    let mut mood = spec_builder("mood").default_verb(Action::Switch).build();
    mood.allowed_states = Some(vec!["happy".into()]);
    mood.regenerate_derived_aliases();
    db.save_field_spec(&mood).unwrap();

    let first = db
        .lookup_alias("happy")
        .unwrap()
        .expect("first save takes alias");
    assert_eq!(first.expands_to, "switch mood happy");

    // Second spec's 'happy' collides: save must skip it and tag the conflict
    // with the owning field.
    let mut interaction = spec_builder("interaction")
        .default_verb(Action::Switch)
        .build();
    interaction.allowed_states = Some(vec!["happy".into()]);
    interaction.regenerate_derived_aliases();
    let report = db.save_field_spec_with_report(&interaction).unwrap();

    assert!(
        report.skipped.iter().any(|c| c.name == "happy"
            && matches!(&c.reason, AliasConflictReason::OwnedByField(f) if f == "mood")),
        "expected skip for 'happy' owned by 'mood', got {:?}",
        report.skipped
    );

    // The original alias is intact — 'happy' still expands to mood's switch.
    let after = db
        .lookup_alias("happy")
        .unwrap()
        .expect("alias survives collision");
    assert_eq!(
        after.expands_to, "switch mood happy",
        "first-save wins; second spec's state alias is silently skipped",
    );
}

// ─── 4. Terminal-verb override: `<field> end` → `end <field>` ────────────────

/// `datum sleep end` rewrites to `datum end sleep` in the CLI pre-pass, even
/// when `sleep` has a bare-field alias (`sleep` → `start sleep`) that would
/// otherwise intercept the first token. Terminal-verb override runs before
/// alias expansion to avoid that collision.
#[test]
fn terminal_verb_end_rewrites_to_end_field() {
    let db = fresh_db();

    // Create a sleep spec with a bare-field alias (`sleep` → `start sleep`).
    let mut sleep = spec_builder("sleep").default_verb(Action::Switch).build();
    sleep.regenerate_derived_aliases();
    db.save_field_spec(&sleep).unwrap();

    run_cli(&["sleep", "-t", "22:00"], &db).expect("start sleep via bare alias");
    run_cli(&["sleep", "end", "-t", "06:00"], &db).expect("terminal-verb override");

    let entries = db.entries_for_field("sleep", None).unwrap();
    assert_eq!(entries.len(), 2, "start + end produce two rows");

    // The close row lands as Verb::Switch (end and stop are synonyms that map
    // to the canonical closing verb).
    let close = entries
        .iter()
        .find(|e| e.verb == Verb::Switch)
        .expect("`sleep end` must route to Verb::Switch");
    assert_eq!(close.field, "sleep");
}

// ─── 5. `<field>e` alias for start/switch-capable fields ─────────────────────

/// A spec with `default_verb ∈ {Start, Switch}` also emits a `<field>e` alias
/// (`sleepe` → `end sleep`) so ergonomic single-token closes work.
#[test]
fn fielde_alias_generated_for_start_capable_fields() {
    let db = fresh_db();

    // Start-capable → emits both `sleep` and `sleepe` aliases.
    let mut sleep = spec_builder("sleep").default_verb(Action::Switch).build();
    sleep.regenerate_derived_aliases();
    db.save_field_spec(&sleep).unwrap();
    let e_alias = db.lookup_alias("sleepe").unwrap().expect("sleepe alias");
    assert_eq!(e_alias.expands_to, "end sleep");

    // Switch-capable → also emits the `<field>e` alias (fields with states
    // are equally duration-capable).
    let mut mood = spec_builder("mood").default_verb(Action::Switch).build();
    mood.regenerate_derived_aliases();
    db.save_field_spec(&mood).unwrap();
    let moode = db.lookup_alias("moode").unwrap().expect("moode alias");
    assert_eq!(moode.expands_to, "end mood");

    // Occur-only fields do NOT get a `<field>e` alias — occur is a point-in-
    // time verb with no ongoing state to close.
    let mut coffee = spec_builder("coffee").default_verb(Action::Occur).build();
    coffee.regenerate_derived_aliases();
    db.save_field_spec(&coffee).unwrap();
    assert!(
        db.lookup_alias("coffeee").unwrap().is_none(),
        "occur default_verb yields no `<field>e` alias",
    );
}

// ─── 6. `datum add` shape inference from temporal keys ───────────────────────

/// `datum add <field> start_time=<t1> end_time=<t2>` infers `shape=block` and
/// writes both timestamps, stripping the temporal keys from `extra_data`.
#[test]
fn add_with_temporal_keys_resolves_shape_correctly() {
    let db = fresh_db();

    // start_time + end_time → block
    run_cli(
        &[
            "add",
            "coffee",
            "start_time=-5m",
            "end_time=now",
            "-t",
            "10:00",
        ],
        &db,
    )
    .expect("add with start+end");

    let e = &db.entries_for_field("coffee", None).unwrap()[0];
    assert_eq!(e.entry_shape, EntryShape::Block);
    assert!(e.occur_time.is_some());
    assert!(e.dur.is_some());
    // Temporal keys get consumed — they don't survive into extra_data.
    assert!(
        e.data.is_none()
            || e.data.as_ref().and_then(|d| d.get("start_time")).is_none()
                && e.data.as_ref().and_then(|d| d.get("end_time")).is_none(),
        "start_time/end_time must be stripped from extra_data, got {:?}",
        e.data
    );

    // start_time only → ongoing semantic (occur_time set, no dur). Under
    // v3 (da-5ns) the storage layer collapses "ongoing" and "point" into
    // the same dur=None shape, so the row_mapper compat shim reads back
    // as EntryShape::Point. The observable invariant — start anchored,
    // no end — is what callers actually rely on.
    let db2 = fresh_db();
    run_cli(&["add", "nap", "start_time=-5m", "-t", "14:00"], &db2).expect("add ongoing");
    let e2 = &db2.entries_for_field("nap", None).unwrap()[0];
    assert!(e2.occur_time.is_some(), "ongoing add anchors occur_time");
    assert!(e2.dur.is_none(), "ongoing add has no dur");

    // no temporal hints → point
    let db3 = fresh_db();
    run_cli(&["add", "ping", "-t", "10:00"], &db3).expect("add point");
    let e3 = &db3.entries_for_field("ping", None).unwrap()[0];
    assert_eq!(e3.entry_shape, EntryShape::Point);
    // Explicit `-t` opts the add back into carrying an occur_time.
    assert!(
        e3.occur_time.is_some(),
        "add with explicit -t must anchor occur_time"
    );
}

/// da-lxyw (regression, broke twice): a bare `datum add` with NO explicit
/// time flag must be TIMELESS — `occur_time == None`. The absence of a time
/// is the defining difference between `add` and `occur`; defaulting it to
/// `now` (or `create_time` at the insert layer) silently turns every add
/// into an occur.
#[test]
fn bare_add_has_no_occur_time() {
    let db = fresh_db();
    run_cli(&["add", "thing", "foo=bar"], &db).expect("bare add");
    let e = &db.entries_for_field("thing", None).unwrap()[0];
    assert!(
        e.occur_time.is_none(),
        "bare `add` (no -t) must be timeless, got occur_time={:?}",
        e.occur_time
    );
    // The user payload still lands.
    assert_eq!(
        e.data.as_ref().and_then(|d| d.get("foo")),
        Some(&serde_json::json!("bar"))
    );
    // A timeless entry slugs as `field:unset` (no timestamp to template).
    assert_eq!(e.slug.as_str(), "thing:unset");
}

// ─── 7. `dur=null` forces point shape ────────────────────────────────────────

/// `datum add field dur=null` is an explicit opt-out: even if a base_time is
/// present, the entry resolves to `EntryShape::Point` with no `end_time`.
#[test]
fn add_with_dur_null_yields_point_shape() {
    let db = fresh_db();

    run_cli(&["add", "note_field", "dur=null", "-t", "10:00"], &db).expect("add with dur=null");

    let e = &db.entries_for_field("note_field", None).unwrap()[0];
    assert_eq!(e.entry_shape, EntryShape::Point);
    assert!(e.dur.is_none(), "dur=null must not set end_time");
    assert!(
        e.data.as_ref().and_then(|d| d.get("dur")).is_none(),
        "dur=null sentinel must be stripped from extra_data, got {:?}",
        e.data
    );
}

// ─── 8. Alias chain is stored on the entry ───────────────────────────────────

/// When an alias is used, the chain of expansions is captured on the entry's
/// `alias_chain` column. Multi-hop aliases land as an ordered JSON array so
/// `datum why` can render them.
///
/// Rebuilt under da-097c (2026-06-02): the original test had the alias
/// `add word srcLang=pt pos=verb` and relied on the legacy "trailing
/// positionals → primary value" path; da-5ns.3 made that error. The
/// rewritten alias declares `-k` slots so positional trail-args fill
/// real data keys, which is the documented daydumb shape for
/// alias-with-payload.
#[test]
fn alias_chain_stored_in_entry() {
    let db = fresh_db();

    // User alias: vbp → add word -k word= -k translation= srcLang=pt pos=verb
    // `-k word=` declares an optional word slot; `-k translation=` declares
    // an optional translation slot. Trailing positionals fill those slots
    // in order — the user-level `vbp correr "to run"` expands to
    // `add word -k word= -k translation= srcLang=pt pos=verb correr "to run"`
    // and the slot fill puts correr in `word` and "to run" in `translation`.
    db.save_alias(&datum_core::field_spec::Alias {
        name: "vbp".into(),
        expands_to: "add word -k word= -k translation= srcLang=pt pos=verb".into(),
        description: None,
    })
    .unwrap();

    run_cli(&["vbp", "correr", "to run"], &db).expect("alias dispatch");

    let e = &db.entries_for_field("word", None).unwrap()[0];
    let chain = e
        .alias_chain
        .as_ref()
        .expect("alias_chain must be populated for alias-expanded invocations");
    let arr = chain.as_array().expect("alias_chain is an array");
    assert_eq!(
        arr.len(),
        1,
        "single-hop expansion → one entry on the chain"
    );
    assert_eq!(arr[0].get("name").and_then(|v| v.as_str()), Some("vbp"));
    assert_eq!(
        arr[0].get("expansion").and_then(|v| v.as_str()),
        Some("add word -k word= -k translation= srcLang=pt pos=verb"),
    );

    // Raw input (the argv the user typed, minus the datum prefix) is also
    // captured alongside the chain.
    let raw = e.raw_input.as_deref().unwrap_or("");
    assert!(
        raw.contains("vbp") && raw.contains("correr"),
        "raw_input must preserve the user's literal invocation, got {raw:?}",
    );
}

// ─── 9. `datum why` renders the alias chain ──────────────────────────────────

/// `datum why <hid>` must run to completion on an entry with a populated
/// `alias_chain` (i.e. the rendering code handles the JSON array form). Dev
/// output goes to stdout via println! — this test guards the code path, and
/// the structural render is covered by inspecting `alias_chain` directly.
///
/// Rebuilt under da-097c: same -k slot pattern as
/// `alias_chain_stored_in_entry` above.
#[test]
fn datum_why_renders_alias_chain() {
    let db = fresh_db();

    // Seed an alias-expanded entry.
    db.save_alias(&datum_core::field_spec::Alias {
        name: "vbp".into(),
        expands_to: "add word -k word= -k translation= srcLang=pt pos=verb".into(),
        description: None,
    })
    .unwrap();
    run_cli(&["vbp", "correr", "to run"], &db).expect("alias dispatch");

    let e = &db.entries_for_field("word", None).unwrap()[0];

    // The why command exits cleanly (handles the array-shaped alias_chain
    // column). --full additionally walks the recorded history trail, so both
    // forms guard the same render path against the populated column.
    run_cli(&["why", &e.slug], &db).expect("datum why human render");
    run_cli(&["why", &e.slug, "--full"], &db).expect("datum why --full render");

    // The entry's persisted chain matches what `why` will render: an ordered
    // list of {name, expansion} steps.
    let arr = e
        .alias_chain
        .as_ref()
        .and_then(|v| v.as_array())
        .expect("alias_chain array present");
    assert!(
        arr.iter()
            .all(|step| step.get("name").is_some() && step.get("expansion").is_some()),
        "every chain step must carry {{name, expansion}} for `datum why`, got {:?}",
        arr,
    );
}
